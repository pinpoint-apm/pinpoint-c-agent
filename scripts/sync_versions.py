#!/usr/bin/env python3
"""Distribute versions.json values to build metadata and generated headers."""

import argparse
import json
import re
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
VERSION_FILE = ROOT / "versions.json"
def load_versions():
    with VERSION_FILE.open(encoding="utf-8") as source:
        versions = json.load(source)

    required = {"php", "python", "python-test", "common", "collector-agent"}
    missing = required.difference(versions)
    if missing:
        raise ValueError(f"versions.json missing keys: {', '.join(sorted(missing))}")

    for key in ("php", "python", "python-test", "common"):
        if not re.fullmatch(r"\d+\.\d+\.\d+", versions[key]):
            raise ValueError(f"Invalid {key} version: {versions[key]!r}")
    if not re.fullmatch(r"v\d+\.\d+\.\d+", versions["collector-agent"]):
        raise ValueError(f"Invalid collector-agent version: {versions['collector-agent']!r}")
    return versions


def update_file(relative_path, pattern, replacement, check_only):
    path = ROOT / relative_path
    original = path.read_text(encoding="utf-8")
    updated, count = re.subn(pattern, replacement, original, count=1, flags=re.MULTILINE)
    if count != 1:
        raise ValueError(f"Expected one managed version in {relative_path}")
    if updated == original:
        return False
    if check_only:
        print(f"Out of sync: {relative_path}")
        return True
    path.write_text(updated, encoding="utf-8")
    print(f"Updated {relative_path}")
    return False


def sync_versions(check_only=False):
    versions = load_versions()
    fields = [
        ("config.m4", r'(^  PINPOINT_PHP_VERSION=")[^"]+("$)', versions["php"]),
        ("php_pinpoint_php.h", r'(^#define PHP_PINPOINT_PHP_VERSION ")[^"]+("$)', versions["php"]),
        ("composer.json", r'("version"\s*:\s*")[^"]+(")', versions["php"]),
        ("setup.py", r'(^VERSION = ")[^"]+("$)', versions["python"]),
        ("setup_pypi_test.py", r'(^VERSION = ")[^"]+("$)', versions["python-test"]),
        ("plugins/PY/pinpointPy/__init__.py", r'(^        return ")[^"]+("$)', versions["python"]),
        ("common/CMakeLists.txt", r'(^set\(PINPOINT_C_AGENT_API_VERSION ")[^"]+("\))', versions["common"]),
        ("common/include/pinpoint/common.h", r'(^#define PINPOINT_C_AGENT_API_VERSION ")[^"]+("$)', versions["common"]),
    ]
    out_of_sync = False
    managed_fields = (
        "config.m4",
        "php_pinpoint_php.h",
        "setup.py",
        "setup_pypi_test.py",
        "plugins/PY/pinpointPy/__init__.py",
        "common/CMakeLists.txt",
        "common/include/common.h.in",
        "common/include/pinpoint/common.h",
        "collector-agent/makefile",
    )
    for relative_path in managed_fields:
        content = (ROOT / relative_path).read_text(encoding="utf-8")
        if "DO NOT edit by hand. Managed by CI (sync-component-versions)." not in content:
            print(f"Missing managed-version comment: {relative_path}")
            out_of_sync = True
    for path, pattern, version in fields:
        out_of_sync |= update_file(path, pattern, rf"\g<1>{version}\g<2>", check_only)
    out_of_sync |= update_file(
        "collector-agent/makefile",
        r"(^TAG := )\S+$",
        rf"\g<1>{versions['collector-agent']}",
        check_only,
    )

    xml = ROOT / "package.xml"
    text = xml.read_text(encoding="utf-8")
    pattern = r"(<version>\s*<release>)[^<]+(</release>\s*<api>)[^<]+(</api>)"
    replacement = rf"\g<1>{versions['php']}\g<2>{versions['php']}\g<3>"
    updated, count = re.subn(pattern, replacement, text, count=1, flags=re.MULTILINE)
    if count != 1:
        raise ValueError("Expected PEAR release/API fields in package.xml")
    if updated != text:
        out_of_sync = True
        if check_only:
            print("Out of sync: package.xml")
        else:
            xml.write_text(updated, encoding="utf-8")
            print("Updated package.xml")

    generated_go = ROOT / "collector-agent/server/version_gen.go"
    expected_go = (
        "// Code generated by make version. DO NOT EDIT.\n"
        "package server\n\n"
        f'var Version = "{versions["collector-agent"]}" // synchronized version\n'
    )
    if check_only:
        if not generated_go.exists() or generated_go.read_text(encoding="utf-8") != expected_go:
            print("Out of sync: collector-agent/server/version_gen.go (run make version)")
            out_of_sync = True
    else:
        subprocess.run(["make", "version"], cwd=ROOT / "collector-agent", check=True)

    if check_only:
        if out_of_sync:
            raise SystemExit(1)
        return



def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated versions differ")
    args = parser.parse_args()
    sync_versions(check_only=args.check)


if __name__ == "__main__":
    main()
